    $start = [Math]::Max(0, $lines.Count - $L.BodyH)
    for ($r = 0; $r -lt $L.BodyH; $r++) {
        $i = $start + $r
        Write-BlobRow $L ($L.BodyTop + $r) $(if ($i -lt $lines.Count) { $lines[$i] } else { '' })
    }
}

function Complete-BlobWork {
