        $k = Read-BlobKey
        if (-not $k) { continue }
        $count = $Blob.MainMenu.Count
        $r0 = $sel % $menuRows; $c0 = [Math]::Floor($sel / $menuRows)
        $choose = $null
        switch ($k.Key) {
            'UpArrow'    { $sel = ($sel - 1 + $count) % $count }
            'DownArrow'  { $sel = ($sel + 1) % $count }
            'LeftArrow'  { if ($c0 -gt 0) { $sel = $sel - $menuRows } }
