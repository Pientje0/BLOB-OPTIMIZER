            -FooterPairs @("$($Blob.Ch.Up)$($Blob.Ch.Down)|Move", 'PgUp/PgDn|Page', 'Enter|Change startup', 'F|Running only / all', 'Esc|Back')
        if ($res.Action -eq 'Back') { return }
        $pos = $res.Index
