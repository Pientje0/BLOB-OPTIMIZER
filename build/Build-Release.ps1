<#
.SYNOPSIS
    Combines the BLOB OPTIMIZER source modules into the single self-contained
    release script BLOB.ps1.

.DESCRIPTION
    - Concatenates src\*.ps1 in dependency order inside one script block, so
      every function and variable disappears when the tool exits.
    - Embeds config\presets.json as a literal here-string.
    - Verifies the output is pure ASCII (safe for PowerShell 5.1 without BOM)
      and parses without syntax errors.
    - Writes BLOB.ps1 and BLOB.ps1.sha256 to the repository root.

.EXAMPLE
    powershell -NoProfile -File .\build\Build-Release.ps1
#>
[CmdletBinding()]
param(
    [string]$Repository = 'Pientje0/BLOB-OPTIMIZER'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Path $PSScriptRoot -Parent
$src = Join-Path $root 'src'
$order = @('Core', 'UI', 'Engine', 'Performance', 'Gaming', 'Tweaks', 'Privacy', 'Services',
           'Startup', 'Cleanup', 'Network', 'Power', 'Restore', 'TweakDetails', 'ExternalTools', 'Apps', 'Prefetch', 'Dashboard',
           'GuiXaml', 'Gui', 'GuiPages', 'GuiSystem', 'GuiApps', 'Main')

$core = Get-Content -LiteralPath (Join-Path $src 'Core.ps1') -Raw
if ($core -notmatch "Version\s*=\s*'([^']+)'") { throw 'Could not read the version from src\Core.ps1' }
$version = $Matches[1]

$presets = Get-Content -LiteralPath (Join-Path $root 'config\presets.json') -Raw
$null = $presets | ConvertFrom-Json   # fail early on invalid JSON
if ($presets -match "(?m)^'@") { throw 'presets.json must not contain a line starting with ''@' }

$sb = New-Object System.Text.StringBuilder
$nl = "`r`n"
[void]$sb.Append(@"
<#
    BLOB OPTIMIZER $version
    Portable Windows optimization utility - window and terminal UI, no installation.

    Launch from PowerShell or Windows Terminal (asks for administrator rights):
        irm https://raw.githubusercontent.com/$Repository/v$version/BLOB.ps1 | iex

    Launch from cmd.exe:
        powershell -NoProfile -ExecutionPolicy Bypass -Command "irm https://raw.githubusercontent.com/$Repository/v$version/BLOB.ps1 | iex"

    Opens the BLOB OPTIMIZER window. Terminal-only interface:
        & ([scriptblock]::Create((irm https://raw.githubusercontent.com/$Repository/v$version/BLOB.ps1))) -Tui

    Dry run (shows what would change, modifies nothing):
        & ([scriptblock]::Create((irm https://raw.githubusercontent.com/$Repository/v$version/BLOB.ps1))) -DryRun

    This file is generated by build\Build-Release.ps1 from the readable
    sources in src\. It contains no encoded or obfuscated code, installs
    nothing and leaves nothing running when closed. When started without
    administrator rights it relaunches itself through the normal Windows
    UAC prompt (use -NoElevate to stay in read-only mode).
    Built: $((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm')) UTC
#>
param([switch]`$DryRun, [switch]`$Tui, [switch]`$NoElevate)

& {
param([bool]`$BlobDryRun, [bool]`$BlobTui, [bool]`$BlobNoElevate, [string]`$BlobScriptPath)
Set-StrictMode -Off

"@)

foreach ($name in $order) {
    $file = Join-Path $src "$name.ps1"
    if (-not (Test-Path -LiteralPath $file)) { throw "Missing source module: $file" }
    [void]$sb.Append("$nl#region ---- $name.ps1 ----$nl")
    [void]$sb.Append((Get-Content -LiteralPath $file -Raw).TrimEnd())
    [void]$sb.Append("$nl#endregion$nl")
    if ($name -eq 'Core') {
        [void]$sb.Append("$nl# Release address, used to relaunch elevated when started with irm | iex$nl`$Blob.ReleaseUrl = 'https://raw.githubusercontent.com/$Repository/v$version/BLOB.ps1'$nl")
        [void]$sb.Append("$nl# Embedded copy of config\presets.json$nl`$Blob.EmbeddedPresets = @'$nl")
        [void]$sb.Append($presets.Trim())
        [void]$sb.Append("$nl'@$nl")
    }
}
[void]$sb.Append("${nl}Start-BlobOptimizer -DryRun `$BlobDryRun -Tui `$BlobTui -NoElevate `$BlobNoElevate -ScriptPath `$BlobScriptPath${nl}} ([bool]`$DryRun) ([bool]`$Tui) ([bool]`$NoElevate) `$PSCommandPath${nl}")

$text = ($sb.ToString() -replace "`r?`n", "`r`n")

# Pure ASCII keeps the script byte-identical across editors and PowerShell 5.1.
$nonAscii = [regex]::Matches($text, '[^\x00-\x7F]')
if ($nonAscii.Count -gt 0) {
    $first = $nonAscii[0].Index
    $line = ($text.Substring(0, $first) -split "`n").Count
    throw "Non-ASCII character '$($nonAscii[0].Value)' found at output line $line. Use [char] code points instead."
}

$tokens = $null; $errors = $null
$null = [System.Management.Automation.Language.Parser]::ParseInput($text, [ref]$tokens, [ref]$errors)
if ($errors.Count -gt 0) {
    $errors | ForEach-Object { Write-Host ("Line {0}: {1}" -f $_.Extent.StartLineNumber, $_.Message) -ForegroundColor Red }
    throw "BLOB.ps1 has $($errors.Count) syntax error(s); release not written."
}

$out = Join-Path $root 'BLOB.ps1'
[IO.File]::WriteAllText($out, $text, (New-Object System.Text.UTF8Encoding($false)))
$hash = (Get-FileHash -LiteralPath $out -Algorithm SHA256).Hash
[IO.File]::WriteAllText("$out.sha256", "$hash  BLOB.ps1`r`n", (New-Object System.Text.UTF8Encoding($false)))

$lines = ($text -split "`n").Count
Write-Host "BLOB OPTIMIZER $version built: $out ($lines lines, $([Math]::Round($text.Length / 1KB)) KB)" -ForegroundColor Green
Write-Host "SHA256 $hash" -ForegroundColor Gray
